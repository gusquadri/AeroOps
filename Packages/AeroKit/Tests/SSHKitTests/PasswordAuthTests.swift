import AeroCore
import Darwin
import Foundation
import Synchronization
import Testing
@testable import SSHKit

/// Password hosts: config, environment, argv, the attempt gate and how the runner feeds it.
/// Fake `ssh` scripts, no server.
@Suite("Password authentication")
struct PasswordAuthTests {
    static let paths = SSHConfigWriterTests.goldenPaths

    static let host = RemoteHost(
        id: UUID(uuidString: "00000000-0000-0000-0000-000000000003")!,
        name: "NAS", address: "nas.local", user: "admin", keyId: "key-1", auth: .password
    )

    static let route = AskpassRoute(
        helper: URL(filePath: "/Applications/AeroOps.app/Contents/MacOS/aeroops-askpass"),
        socket: paths.askpassSocket
    )

    // MARK: Config and environment

    @Test("a password host offers no key and sends one password per connection (golden)")
    func golden() throws {
        // The key id is kept for switching back, but never offered while the host uses a password.
        let rendering = try SSHConfigWriter(context: SSHContext(paths: Self.paths)).render([Self.host])
        #expect(rendering.rejected.isEmpty)
        #expect(rendering.text == """
        # Generated by AeroOps. Do not edit: this file is rewritten whenever hosts change.

        Host aero-00000000-0000-0000-0000-000000000003
          HostName nas.local
          User admin
          Port 22
          IdentityAgent none
          IdentityFile none
          IdentitiesOnly yes
          PubkeyAuthentication no
          PreferredAuthentications password,keyboard-interactive
          NumberOfPasswordPrompts 1
          UserKnownHostsFile /tmp/aero-golden/.aeroops/synced_known_hosts /tmp/aero-golden/.aeroops/known_hosts
          StrictHostKeyChecking yes
          ControlMaster auto
          ControlPath /tmp/aero-golden/.aeroops/cm/37f6476c15b1883d
          ControlPersist 10m
          ServerAliveInterval 15
          ServerAliveCountMax 3
          ConnectTimeout 8
          SendEnv LANG LC_* COLORTERM
          LogLevel ERROR

        """)

        // The system ssh-agent option does not hand a password host the user's keys either.
        let system = try SSHConfigWriter(context: SSHContext(paths: Self.paths, agent: .system)).render([Self.host]).text
        #expect(system.contains("\n  IdentityAgent none\n"))
        #expect(!system.contains("SSH_AUTH_SOCK"))
    }

    @Test("ssh -G reads the password block back as intended")
    func sshAcceptsConfig() async throws {
        let scratch = try ScratchDirectory()
        let paths = scratch.paths()
        try SSHConfigWriter(context: SSHContext(paths: paths)).write([SSHConfigWriterTests.hostA, Self.host])
        let result = try await runTool("/usr/bin/ssh", ["-G", "-F", paths.sshConfig.filePath, Self.host.sshAlias])
        #expect(result.status == 0, "\(result.stderr)")
        // OpenSSH 10 prints PubkeyAuthentication as true/false; older releases as yes/no.
        #expect(result.stdout.contains("\npubkeyauthentication false\n") || result.stdout.contains("\npubkeyauthentication no\n"))
        for line in [
            "passwordauthentication yes",
            "preferredauthentications password,keyboard-interactive",
            "numberofpasswordprompts 1",
            "identityagent none",
            "batchmode no",
        ] {
            #expect(result.stdout.contains("\n\(line)\n"), "missing \(line)")
        }
        #expect(!result.stdout.contains("key-1.pub"))

        // The key host next to it is unaffected.
        let keyHost = try await runTool("/usr/bin/ssh", ["-G", "-F", paths.sshConfig.filePath, SSHConfigWriterTests.hostA.sshAlias])
        #expect(keyHost.stdout.contains("\nnumberofpasswordprompts 3\n"))
        #expect(!keyHost.stdout.contains("\npubkeyauthentication false\n") && !keyHost.stdout.contains("\npubkeyauthentication no\n"))
    }

    @Test("only password hosts with an askpass route get the askpass environment")
    func environment() {
        var context = SSHContext(paths: Self.paths)
        let base = ["SSH_AUTH_SOCK": "/tmp/aero-golden/.aeroops/agent.sock"]
        #expect(!context.usesAskpass(Self.host))
        #expect(context.environment(for: Self.host) == base)

        context.askpass = Self.route
        #expect(context.usesAskpass(Self.host))
        #expect(!context.usesAskpass(SSHConfigWriterTests.hostA))
        #expect(context.environment(for: SSHConfigWriterTests.hostA) == base)
        #expect(context.environment(for: Self.host) == base.merging([
            "SSH_ASKPASS": "/Applications/AeroOps.app/Contents/MacOS/aeroops-askpass",
            "SSH_ASKPASS_REQUIRE": "force",
            "AEROOPS_ASKPASS_SOCKET": "/tmp/aero-golden/.aeroops/askpass.sock",
            "AEROOPS_ASKPASS_HOST": "00000000-0000-0000-0000-000000000003",
        ]) { $1 })

        context.askpassToken = "0123456789abcdef0123456789abcdef"
        #expect(context.environment(for: Self.host)["AEROOPS_ASKPASS_TOKEN"] == "0123456789abcdef0123456789abcdef")
        #expect(context.environment(for: SSHConfigWriterTests.hostA)["AEROOPS_ASKPASS_TOKEN"] == nil)
    }

    @Test("terminal tabs use askpass when they can, else prompt in the tab with three tries")
    func terminalCommand() {
        var context = SSHContext(paths: Self.paths)
        let config = "/tmp/aero-golden/.aeroops/ssh_config"
        let prompting = context.terminalCommand(for: Self.host)
        #expect(prompting.argv == ["/usr/bin/ssh", "-F", config, "-o", "NumberOfPasswordPrompts=3", Self.host.sshAlias])
        #expect(prompting.environment["SSH_ASKPASS"] == nil)

        context.askpass = Self.route
        let asking = context.terminalCommand(for: Self.host)
        #expect(asking.argv == ["/usr/bin/ssh", "-F", config, Self.host.sshAlias])
        #expect(asking.environment["SSH_ASKPASS_REQUIRE"] == "force")
        #expect(asking.environment["AEROOPS_ASKPASS_HOST"] == Self.host.id.uuidString)
    }

    @Test("background ssh drops BatchMode only for password hosts it can answer")
    func argv() async throws {
        let scratch = try ScratchDirectory()
        let echo = try scratch.script("echo-ssh", #"printf '%s\n' "$@"; printf 'ASKPASS=%s|%s|%s\n' "$SSH_ASKPASS" "$SSH_ASKPASS_REQUIRE" "$AEROOPS_ASKPASS_HOST""#)
        let paths = scratch.paths()
        var context = SSHContext(paths: paths, sshExecutable: echo)
        let config = paths.sshConfig.filePath

        // No route: BatchMode stays, so ssh fails instead of prompting nobody.
        let batch = try await SSHRunner(context: context).run("uptime", on: Self.host)
        #expect(batch.stdoutString.split(separator: "\n").map(String.init) == [
            "-F", config, "-o", "BatchMode=yes", "--", Self.host.sshAlias, "uptime", "ASKPASS=||",
        ])

        context.askpass = AskpassRoute(helper: scratch.file("aeroops-askpass"), socket: paths.askpassSocket)
        let runner = SSHRunner(context: context)
        let asking = try await runner.run("uptime", on: Self.host)
        #expect(asking.stdoutString.split(separator: "\n").map(String.init) == [
            "-F", config, "--", Self.host.sshAlias, "uptime",
            "ASKPASS=\(scratch.file("aeroops-askpass").filePath)|force|\(Self.host.id.uuidString)",
        ])
        #expect(!runner.commandLine("uptime", on: Self.host).argv.contains("BatchMode=yes"))
        #expect(runner.commandLine("uptime", on: SSHConfigWriterTests.hostA).argv.contains("BatchMode=yes"))
    }

    @Test("a signal with the helper's message is an authentication failure")
    func helperTermination() async throws {
        let scratch = try ScratchDirectory()
        let killed = try scratch.script("killed-ssh", "echo 'aeroops-askpass: no password is saved for the host' >&2; kill -TERM $$")
        let result = try await SSHRunner(context: SSHContext(paths: scratch.paths(), sshExecutable: killed)).run("true", alias: "aero-test")
        #expect(result.signal == SIGTERM)
        #expect(result.transportError == .authFailed)

        let other = try scratch.script("other-ssh", "echo 'something else' >&2; kill -TERM $$")
        let plain = try await SSHRunner(context: SSHContext(paths: scratch.paths(), sshExecutable: other)).run("true", alias: "aero-test")
        #expect(plain.transportError == .other("ssh was terminated by signal \(SIGTERM)"))
        #expect(SSHError.classify(stderr: "aeroops-askpass: the server rejected the password and asked again\n") == .authFailed)
    }

    // MARK: Runner and gate

    /// A runner for a password host whose fake ssh appends a line to `runs` and then runs `body`.
    private func runner(_ scratch: ScratchDirectory, gate: PasswordAttemptGate, askpass: Bool = true, body: String) throws -> SSHRunner {
        let fake = try scratch.script("ssh", "echo run >> \(ShellQuote.quote(scratch.file("runs").filePath))\n" + body)
        var context = SSHContext(paths: scratch.paths(), sshExecutable: fake)
        if askpass { context.askpass = AskpassRoute(helper: scratch.file("aeroops-askpass"), socket: scratch.paths().askpassSocket) }
        return SSHRunner(context: context, passwords: gate)
    }

    private func runs(_ scratch: ScratchDirectory) -> Int {
        scratch.read("runs")?.split(separator: "\n").count ?? 0
    }

    @Test("a rejected password closes the gate: no ssh starts until it is reset")
    func rejectionLatches() async throws {
        let scratch = try ScratchDirectory()
        let gate = PasswordAttemptGate { _ in true }
        let runner = try runner(scratch, gate: gate, body: "echo 'admin@nas.local: Permission denied (password).' >&2; exit 255")

        let first = try await runner.run("uptime", on: Self.host)
        #expect(first.transportError == .authFailed)
        #expect(await gate.isRejected(Self.host.id))
        await #expect(throws: SSHError.authFailed) { try await runner.run("uptime", on: Self.host) }
        await #expect(throws: SSHError.authFailed) { try await runner.stream("uptime", on: Self.host) }
        #expect(runs(scratch) == 1)

        await gate.reset(Self.host.id)
        _ = try await runner.run("uptime", on: Self.host)
        #expect(runs(scratch) == 2)

        // Key hosts never wait on the gate.
        let key = RemoteHost.test()
        _ = try await runner.run("uptime", on: key)
        #expect(runs(scratch) == 3)
    }

    @Test("a login proves the password; anything else just frees the next try")
    func settles() async throws {
        let scratch = try ScratchDirectory()
        let gate = PasswordAttemptGate(probeWindow: .seconds(60)) { _ in true }
        let ok = try runner(scratch, gate: gate, body: "exit 0")
        _ = try await ok.run("uptime", on: Self.host)
        #expect(await gate.isProven(Self.host.id))
        #expect(await !gate.isRejected(Self.host.id))

        // Unreachable: says nothing about the password, so neither proven nor rejected, and the
        // next run does not wait for the probe window.
        await gate.reset(Self.host.id)
        let refused = try runner(scratch, gate: gate, body: "echo 'ssh: connect to host nas.local port 22: Connection refused' >&2; exit 255")
        #expect(try await refused.run("uptime", on: Self.host).transportError == .connectionRefused)
        #expect(await !gate.isProven(Self.host.id))
        #expect(await !gate.isRejected(Self.host.id))
        let start = ContinuousClock.now
        _ = try await refused.run("uptime", on: Self.host)
        #expect(ContinuousClock.now - start < .seconds(10))

        // A launch failure frees it too.
        let missing = SSHRunner(
            context: SSHContext(paths: scratch.paths(), sshExecutable: scratch.file("no-such-ssh")), passwords: gate)
        await #expect(throws: (any Error).self) { try await missing.run("uptime", on: Self.host) }
        let again = ContinuousClock.now
        try await gate.admit(Self.host)
        #expect(ContinuousClock.now - again < .seconds(10))
    }

    @Test("without an askpass route, a failed login sent no password and does not latch")
    func noRouteDoesNotLatch() async throws {
        let scratch = try ScratchDirectory()
        let gate = PasswordAttemptGate { _ in true }
        let runner = try runner(scratch, gate: gate, askpass: false, body: "echo 'admin@nas.local: Permission denied (password).' >&2; exit 255")
        #expect(try await runner.run("uptime", on: Self.host).transportError == .authFailed)
        #expect(await !gate.isRejected(Self.host.id))
        _ = try await runner.run("uptime", on: Self.host)
        #expect(runs(scratch) == 2)
    }

    @Test("the helper's refusal (ssh terminated) closes the gate")
    func helperRefusalLatches() async throws {
        let scratch = try ScratchDirectory()
        let gate = PasswordAttemptGate { _ in true }
        let runner = try runner(scratch, gate: gate, body: "echo 'aeroops-askpass: the server rejected the password and asked again' >&2; kill -TERM $$")
        #expect(try await runner.run("uptime", on: Self.host).transportError == .authFailed)
        #expect(await gate.isRejected(Self.host.id))
    }

    @Test("no saved password: refused before ssh starts; key hosts always pass")
    func noPassword() async throws {
        let saved = Mutex(false)
        let gate = PasswordAttemptGate { _ in saved.withLock { $0 } }
        await #expect(throws: SSHError.authFailed) { try await gate.admit(Self.host) }
        try await gate.admit(RemoteHost.test())
        saved.withLock { $0 = true }
        try await gate.admit(Self.host)
    }

    @Test("an unproven host lets one login through at a time")
    func serializesFirstLogins() async throws {
        let gate = PasswordAttemptGate(probeWindow: .seconds(60)) { _ in true }
        let host = Self.host
        try await gate.admit(host)
        let admitted = Mutex(false)
        let waiter = Task {
            try await gate.admit(host)
            admitted.withLock { $0 = true }
        }
        try await Task.sleep(for: .milliseconds(300))
        #expect(!admitted.withLock { $0 })
        await gate.accept(host.id)
        try await waiter.value
        #expect(admitted.withLock { $0 })

        // Proven: everyone passes at once.
        try await gate.admit(host)
        try await gate.admit(host)

        // After a reset the next login is a probe again; release lets the next one try.
        await gate.reset(host.id)
        try await gate.admit(host)
        await gate.release(host.id)
        try await gate.admit(host)
    }

    @Test("a rejection or cancellation ends the wait; the probe window ends it on its own")
    func waitEnds() async throws {
        let host = Self.host
        let gate = PasswordAttemptGate(probeWindow: .seconds(60)) { _ in true }
        try await gate.admit(host)
        let rejected = Task { try await gate.admit(host) }
        let cancelled = Task { try await gate.admit(host) }
        try await Task.sleep(for: .milliseconds(150))
        cancelled.cancel()
        await #expect(throws: CancellationError.self) { try await cancelled.value }
        await gate.reject(host.id)
        await #expect(throws: SSHError.authFailed) { try await rejected.value }

        let short = PasswordAttemptGate(probeWindow: .milliseconds(300)) { _ in true }
        try await short.admit(host)
        let start = ContinuousClock.now
        try await short.admit(host)
        let waited = ContinuousClock.now - start
        #expect(waited >= .milliseconds(250) && waited < .seconds(5))
    }

    @Test("changes() publishes the rejected set now and on every change")
    func changes() async {
        let gate = PasswordAttemptGate { _ in true }
        let id = Self.host.id
        var updates = await gate.changes().makeAsyncIterator()
        #expect(await updates.next() == [])
        await gate.reject(id)
        #expect(await updates.next() == [id])
        await gate.reject(id) // already rejected: nothing new
        await gate.reset(id)
        #expect(await updates.next() == [])
        #expect(await gate.rejectedHosts.isEmpty)
    }
}
