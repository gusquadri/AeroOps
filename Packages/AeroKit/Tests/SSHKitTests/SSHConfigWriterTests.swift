import AeroCore
import Darwin
import Foundation
import Testing
@testable import SSHKit

@Suite("SSHConfigWriter")
struct SSHConfigWriterTests {
    static let goldenPaths = AeroPaths(
        dotDirectory: URL(filePath: "/tmp/aero-golden/.aeroops/", directoryHint: .isDirectory),
        applicationSupport: URL(filePath: "/tmp/aero-golden/support/", directoryHint: .isDirectory)
    )

    static let hostA = RemoteHost(
        id: UUID(uuidString: "6F9619FF-8B86-D011-B42D-00C04FC964FF")!,
        name: "Web 1", address: "10.0.0.12", user: "deploy", keyId: "key-1"
    )
    static let hostB = RemoteHost(
        id: UUID(uuidString: "00000000-0000-0000-0000-000000000002")!,
        name: "Link local", address: "fe80::1%en0", port: 2222, user: "dev"
    )

    @Test("renders the plan's block per host (golden)")
    func golden() throws {
        let writer = SSHConfigWriter(context: SSHContext(paths: Self.goldenPaths))
        let rendering = try writer.render([Self.hostA, Self.hostB])
        #expect(rendering.rejected.isEmpty)
        #expect(rendering.included == [Self.hostA.id, Self.hostB.id])
        #expect(rendering.text == """
        # Generated by AeroOps. Do not edit: this file is rewritten whenever hosts change.

        Host aero-6f9619ff-8b86-d011-b42d-00c04fc964ff
          HostName 10.0.0.12
          User deploy
          Port 22
          IdentityAgent /tmp/aero-golden/.aeroops/agent.sock
          IdentityFile /tmp/aero-golden/.aeroops/pub/key-1.pub
          IdentitiesOnly yes
          UserKnownHostsFile /tmp/aero-golden/.aeroops/known_hosts
          StrictHostKeyChecking yes
          ControlMaster auto
          ControlPath /tmp/aero-golden/.aeroops/cm/%C
          ControlPersist 10m
          ServerAliveInterval 15
          ServerAliveCountMax 3
          ConnectTimeout 8
          LogLevel ERROR

        Host aero-00000000-0000-0000-0000-000000000002
          HostName fe80::1%%en0
          User dev
          Port 2222
          IdentityAgent /tmp/aero-golden/.aeroops/agent.sock
          IdentityFile none
          IdentitiesOnly yes
          UserKnownHostsFile /tmp/aero-golden/.aeroops/known_hosts
          StrictHostKeyChecking yes
          ControlMaster auto
          ControlPath /tmp/aero-golden/.aeroops/cm/%C
          ControlPersist 10m
          ServerAliveInterval 15
          ServerAliveCountMax 3
          ConnectTimeout 8
          LogLevel ERROR

        """)
        #expect(!rendering.text.contains("BatchMode"))
    }

    @Test("an empty host list renders just the header")
    func empty() throws {
        let text = try SSHConfigWriter(context: SSHContext(paths: Self.goldenPaths)).render([]).text
        #expect(text == SSHConfigWriter.header + "\n")
    }

    @Test("rejects unsafe host fields and keeps the other hosts", arguments: [
        RemoteHost.test(address: "evil\n  ProxyCommand touch /tmp/pwned"),
        RemoteHost.test(address: "host name"),
        RemoteHost.test(address: "-oProxyCommand=x"),
        RemoteHost.test(address: ""),
        RemoteHost.test(address: "a\"b"),
        RemoteHost.test(user: "dev\nHost *"),
        RemoteHost.test(user: "-l"),
        RemoteHost.test(user: "a b"),
        RemoteHost.test(port: 0),
        RemoteHost.test(port: 65536),
        RemoteHost.test(keyId: "../../.ssh/id_ed25519"),
        RemoteHost.test(keyId: "k\n"),
        RemoteHost.test(keyId: ".hidden"),
    ])
    func rejectsUnsafe(_ bad: RemoteHost) throws {
        let writer = SSHConfigWriter(context: SSHContext(paths: Self.goldenPaths))
        let rendering = try writer.render([Self.hostA, bad])
        #expect(rendering.included == [Self.hostA.id])
        #expect(rendering.rejected[bad.id] != nil)
        #expect(!rendering.text.contains(bad.sshAlias))
        #expect(throws: SSHConfigError.self) { try writer.validate(bad) }
    }

    @Test("quotes paths with spaces and escapes % in token-expanding directives")
    func quoting() throws {
        let paths = AeroPaths(
            dotDirectory: URL(filePath: "/tmp/aero q 100%/.aeroops/", directoryHint: .isDirectory),
            applicationSupport: URL(filePath: "/tmp/x/", directoryHint: .isDirectory)
        )
        let text = try SSHConfigWriter(context: SSHContext(paths: paths)).render([Self.hostA]).text
        #expect(text.contains(#"  IdentityAgent "/tmp/aero q 100%%/.aeroops/agent.sock""#))
        #expect(text.contains(#"  IdentityFile "/tmp/aero q 100%%/.aeroops/pub/key-1.pub""#))
        #expect(text.contains(#"  ControlPath "/tmp/aero q 100%%/.aeroops/cm/%C""#))
    }

    @Test("refuses paths ssh_config cannot represent")
    func badPaths() {
        for dot in ["/tmp/a\"b/", "/tmp/a\\b/", "/tmp/$HOME/", "/tmp/a\nb/"] {
            let paths = AeroPaths(
                dotDirectory: URL(filePath: dot, directoryHint: .isDirectory),
                applicationSupport: URL(filePath: "/tmp/x/", directoryHint: .isDirectory)
            )
            let rendering = try? SSHConfigWriter(context: SSHContext(paths: paths)).render([Self.hostA])
            #expect(rendering?.included.isEmpty ?? true, "\(dot)")
        }
    }

    @Test("refuses a ControlPath that cannot fit in sun_path")
    func socketPathTooLong() {
        let long = "/tmp/" + String(repeating: "x", count: 60) + "/"
        let paths = AeroPaths(
            dotDirectory: URL(filePath: long, directoryHint: .isDirectory),
            applicationSupport: URL(filePath: "/tmp/x/", directoryHint: .isDirectory)
        )
        #expect(throws: SSHConfigError.self) {
            try SSHConfigWriter(context: SSHContext(paths: paths)).render([Self.hostA])
        }
    }

    @Test("ssh -G reads the generated file back as intended")
    func sshAcceptsConfig() async throws {
        let scratch = try ScratchDirectory()
        let paths = AeroPaths(
            dotDirectory: scratch.url.appending(path: "a b%c", directoryHint: .isDirectory),
            applicationSupport: scratch.url.appending(path: "s", directoryHint: .isDirectory)
        )
        let writer = SSHConfigWriter(context: SSHContext(paths: paths))
        try writer.write([Self.hostA, Self.hostB])
        let result = try await runTool("/usr/bin/ssh", ["-G", "-F", paths.sshConfig.filePath, Self.hostA.sshAlias])
        #expect(result.status == 0, "\(result.stderr)")
        let options = Dictionary(
            result.stdout.split(separator: "\n").compactMap { line -> (String, String)? in
                guard let space = line.firstIndex(of: " ") else { return nil }
                return (String(line[..<space]), String(line[line.index(after: space)...]))
            },
            uniquingKeysWith: { first, _ in first }
        )
        let dot = scratch.path + "/a b%c"
        #expect(options["hostname"] == "10.0.0.12")
        #expect(options["user"] == "deploy")
        #expect(options["port"] == "22")
        #expect(options["identitiesonly"] == "yes")
        #expect(options["stricthostkeychecking"] == "true")
        #expect(options["controlmaster"] == "auto")
        #expect(options["controlpersist"] == "600")
        #expect(options["connecttimeout"] == "8")
        #expect(options["batchmode"] == "no")
        #expect(options["identityagent"]?.contains(dot + "/agent.sock") == true, "\(options["identityagent"] ?? "-")")
        // -G prints IdentityFile unexpanded; ssh percent-expands it (%% -> %) when loading the key.
        #expect(options["identityfile"]?.contains(scratch.path + "/a b%%c/pub/key-1.pub") == true, "\(options["identityfile"] ?? "-")")
        #expect(options["userknownhostsfile"]?.contains(dot + "/known_hosts") == true)

        let linkLocal = try await runTool("/usr/bin/ssh", ["-G", "-F", paths.sshConfig.filePath, Self.hostB.sshAlias])
        #expect(linkLocal.stdout.contains("\nhostname fe80::1%en0\n"))
        #expect(linkLocal.stdout.contains("\nidentityfile none\n"))
    }

    @Test("write creates owner-only directories and an atomic 0600 file")
    func writesFiles() throws {
        let scratch = try ScratchDirectory()
        let paths = scratch.paths()
        let writer = SSHConfigWriter(context: SSHContext(paths: paths))
        let rendering = try writer.write([Self.hostA])
        #expect(try String(contentsOf: paths.sshConfig, encoding: .utf8) == rendering.text)
        #expect(mode(paths.sshConfig) == 0o600)
        #expect(mode(paths.dotDirectory) == 0o700)
        #expect(mode(paths.controlMasterDirectory) == 0o700)
        #expect(mode(paths.publicKeysDirectory) == 0o700)

        // Rewriting replaces the file and leaves no temporaries behind.
        try writer.write([])
        #expect(try String(contentsOf: paths.sshConfig, encoding: .utf8) == SSHConfigWriter.header + "\n")
        let leftovers = try FileManager.default.contentsOfDirectory(atPath: paths.dotDirectory.filePath)
        #expect(leftovers.sorted() == ["cm", "pub", "ssh_config"])
    }

    @Test("terminal command is ssh -F <config> <alias> with the agent socket")
    func terminalCommand() {
        let context = SSHContext(paths: Self.goldenPaths)
        let command = context.terminalCommand(for: Self.hostA)
        #expect(command.argv == [
            "/usr/bin/ssh", "-F", "/tmp/aero-golden/.aeroops/ssh_config", "aero-6f9619ff-8b86-d011-b42d-00c04fc964ff",
        ])
        #expect(command.environment == ["SSH_AUTH_SOCK": "/tmp/aero-golden/.aeroops/agent.sock"])
    }

    @Test("system ssh-agent fallback: IdentityAgent SSH_AUTH_SOCK, no key files, no SSH_AUTH_SOCK override")
    func systemAgent() async throws {
        let scratch = try ScratchDirectory()
        let paths = scratch.paths()
        let context = SSHContext(paths: paths, agent: .system)
        let writer = SSHConfigWriter(context: context)
        let rendering = try writer.write([Self.hostA, Self.hostB])
        #expect(rendering.rejected.isEmpty)
        #expect(!rendering.text.contains("agent.sock"))
        #expect(!rendering.text.contains("/pub/"))
        let block = rendering.text.components(separatedBy: "\n\n")[1]
        #expect(block.contains("\n  IdentityAgent SSH_AUTH_SOCK\n"))
        #expect(block.contains("\n  IdentityFile none\n"))
        #expect(block.contains("\n  IdentitiesOnly no\n"))
        #expect(block.contains("\n  StrictHostKeyChecking yes\n"))
        #expect(context.environmentOverrides.isEmpty)
        #expect(context.terminalCommand(for: Self.hostA).environment.isEmpty)

        // ssh resolves the token from its own environment.
        let result = try await runTool(
            "/usr/bin/env", ["SSH_AUTH_SOCK=/tmp/sys-agent.sock", "/usr/bin/ssh", "-G", "-F", paths.sshConfig.filePath, Self.hostA.sshAlias]
        )
        #expect(result.status == 0, "\(result.stderr)")
        #expect(result.stdout.contains("\nidentityagent SSH_AUTH_SOCK\n") || result.stdout.contains("\nidentityagent /tmp/sys-agent.sock\n"), "\(result.stdout)")
        #expect(result.stdout.contains("\nidentitiesonly no\n"))

        // Key ids are still validated, so a bad one cannot hide while the fallback is on.
        let bad = RemoteHost.test(keyId: "../x")
        #expect(throws: SSHConfigError.invalidKeyID("../x")) { try writer.validate(bad) }
    }

    @Test("a config file override redirects both the writer and the runner's -F")
    func configFileOverride() throws {
        let scratch = try ScratchDirectory()
        var context = SSHContext(paths: scratch.paths())
        context.configFileOverride = scratch.file("probe_config")
        try SSHConfigWriter(context: context).write([Self.hostA])
        #expect(scratch.read("probe_config")?.contains("Host \(Self.hostA.sshAlias)") == true)
        #expect(!FileManager.default.fileExists(atPath: context.paths.sshConfig.filePath))
        let argv = SSHRunner(context: context).commandLine("true", on: Self.hostA).arguments
        #expect(Array(argv.prefix(2)) == ["-F", scratch.file("probe_config").filePath])
    }

    @Test("known_hosts names follow ssh: lower case, [host]:port unless 22")
    func knownHostsNames() {
        #expect(RemoteHost.test(address: "Example.COM", port: 22).knownHostsName == "example.com")
        #expect(RemoteHost.test(address: "LOCALHOST", port: 2222).knownHostsName == "[localhost]:2222")
    }

    private func mode(_ url: URL) -> mode_t {
        var info = stat()
        lstat(url.filePath, &info)
        return info.st_mode & 0o7777
    }
}
