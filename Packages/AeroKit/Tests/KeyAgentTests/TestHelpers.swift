/// A short directory under `/tmp` (socket paths must fit in 104 bytes), removed by `remove()`.
struct TempDirectory {
    let url: URL
    var path: String { url.path }

    init() throws {
        url = URL(fileURLWithPath: "/tmp/aeroops-t\(String(UInt32.random(in: 0...UInt32.max), radix: 16))", isDirectory: true)
        try FileManager.default.createDirectory(at: url, withIntermediateDirectories: false, attributes: [.posixPermissions: 0o700])
    }

    func appending(_ component: String) -> URL { url.appending(path: component) }

    func remove() { try? FileManager.default.removeItem(at: url) }
}

struct ProcessResult {
    var status: Int32
    var stdout: String
    var stderr: String
}

/// Runs a program without blocking a concurrency-pool thread.
func runProcess(_ path: String, _ arguments: [String], environment: [String: String]? = nil, timeout: Duration = .seconds(30)) async throws -> ProcessResult {
    let process = Process()
    process.executableURL = URL(fileURLWithPath: path)
    process.arguments = arguments
    if let environment { process.environment = environment }
    let out = Pipe(), err = Pipe()
    process.standardOutput = out
    process.standardError = err
    process.standardInput = FileHandle.nullDevice
    let box = ProcessBox(process)
    let watchdog = Task {
        try await Task.sleep(for: timeout)
        if box.process.isRunning { box.process.terminate() }
    }
    defer { watchdog.cancel() }
    let status: Int32 = try await withCheckedThrowingContinuation { continuation in
        process.terminationHandler = { continuation.resume(returning: $0.terminationStatus) }
        do { try process.run() } catch { continuation.resume(throwing: error) }
    }
    return ProcessResult(
        status: status,
        stdout: String(decoding: out.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self),
        stderr: String(decoding: err.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self))
}

private final class ProcessBox: @unchecked Sendable {
    let process: Process
    init(_ process: Process) { self.process = process }
}

/// A key generated by `ssh-keygen` at test time. The private key file is deleted as soon as it
/// has been read; nothing is ever committed.
struct GeneratedOpenSSHKey {
    var privateKeyText: String
    var publicKeyLine: String
    /// `ssh-keygen -lf` output's fingerprint field.
    var fingerprint: String
    var publicKeyFile: URL

    static func make(type: String, bits: Int? = nil, passphrase: String = "", format: String? = nil, comment: String = "test@aeroops", in directory: TempDirectory) async throws -> GeneratedOpenSSHKey {
        let base = directory.appending("k-\(UUID().uuidString.prefix(8))")
        var args = ["-q", "-t", type, "-N", passphrase, "-C", comment, "-f", base.path]
        if let bits { args += ["-b", String(bits)] }
        if let format { args += ["-m", format] }
        let result = try await runProcess("/usr/bin/ssh-keygen", args)
        guard result.status == 0 else { throw TestFailure("ssh-keygen \(args) failed: \(result.stderr)") }
        let privateText = try String(contentsOf: base, encoding: .utf8)
        try FileManager.default.removeItem(at: base)
        let pub = base.appendingPathExtension("pub")
        let line = try String(contentsOf: pub, encoding: .utf8).trimmingCharacters(in: .whitespacesAndNewlines)
        let lf = try await runProcess("/usr/bin/ssh-keygen", ["-l", "-E", "sha256", "-f", pub.path])
        let fields = lf.stdout.split(separator: " ")
        guard lf.status == 0, fields.count >= 2 else { throw TestFailure("ssh-keygen -lf failed: \(lf.stderr)") }
        return GeneratedOpenSSHKey(privateKeyText: privateText, publicKeyLine: line, fingerprint: String(fields[1]), publicKeyFile: pub)
    }
}

