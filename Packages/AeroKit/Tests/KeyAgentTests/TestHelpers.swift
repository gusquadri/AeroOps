/// Builds the data ssh signs for `publickey-hostbound-v00@openssh.com`.
func userAuthData(sessionID: [UInt8], user: String, algorithm: String, keyBlob: [UInt8], hostKey: [UInt8]?) -> [UInt8] {
    var w = SSHWriter()
    w.string(sessionID)
    w.byte(50)
    w.string(user)
    w.string("ssh-connection")
    w.string(hostKey == nil ? "publickey" : "publickey-hostbound-v00@openssh.com")
    w.bool(true)
    w.string(algorithm)
    w.string(keyBlob)
    if let hostKey { w.string(hostKey) }
    return w.bytes
}

func signRequestMessage(keyBlob: [UInt8], data: [UInt8], flags: UInt32) -> [UInt8] {
    var w = SSHWriter()
    w.byte(AgentMessage.signRequest)
    w.string(keyBlob)
    w.string(data)
    w.uint32(flags)
    return w.bytes
}

func sessionBindMessage(hostKey: [UInt8], sessionID: [UInt8], forwarding: Bool) -> [UInt8] {
    var w = SSHWriter()
    w.byte(AgentMessage.extensionRequest)
    w.string(AgentMessage.sessionBindExtension)
    w.string(hostKey)
    w.string(sessionID)
    w.string([UInt8](repeating: 1, count: 83))
    w.bool(forwarding)
    return w.bytes
}

/// Parses `IDENTITIES_ANSWER` into (blob, comment) pairs.
func parseIdentities(_ reply: [UInt8]) throws -> [(blob: [UInt8], comment: String)] {
    var r = SSHReader(reply)
    guard try r.byte() == AgentMessage.identitiesAnswer else { throw TestFailure("not IDENTITIES_ANSWER") }
    let count = try r.uint32()
    var result: [(blob: [UInt8], comment: String)] = []
    for _ in 0..<count { result.append((try r.string(), try r.text())) }
    return result
}

/// The signature blob from a `SIGN_RESPONSE`.
func parseSignResponse(_ reply: [UInt8]) throws -> [UInt8] {
    var r = SSHReader(reply)
    guard try r.byte() == AgentMessage.signResponse else { throw TestFailure("not SIGN_RESPONSE: \(reply.first ?? 0)") }
    return try r.string()
}

func signatureAlgorithm(_ blob: [UInt8]) -> String? {
    var r = SSHReader(blob)
    return try? r.text()
}

/// Generates a 2048-bit RSA key in memory and returns its PKCS#1 DER.
func makeRSAKeyDER(bits: Int = 2048) throws -> Data {
    let attributes: [CFString: Any] = [kSecAttrKeyType: kSecAttrKeyTypeRSA, kSecAttrKeySizeInBits: bits]
    var error: Unmanaged<CFError>?
    guard let key = SecKeyCreateRandomKey(attributes as CFDictionary, &error),
          let der = SecKeyCopyExternalRepresentation(key, &error) as Data? else {
        throw TestFailure("RSA generation failed: \(RSASigningKey.describe(error))")
    }
    return der
}

/// A blocking ssh-agent client for tests. I/O runs on a Dispatch thread, never on the Swift
/// concurrency pool, which the server's handler needs.
final class AgentTestClient: Sendable {
    let fd: Int32

    init(path: String) throws {
        fd = socket(AF_UNIX, SOCK_STREAM, 0)
        guard fd >= 0 else { throw TestFailure("socket: \(errno)") }
        var on: Int32 = 1
        setsockopt(fd, SOL_SOCKET, SO_NOSIGPIPE, &on, socklen_t(MemoryLayout<Int32>.size))
        var timeout = timeval(tv_sec: 10, tv_usec: 0)
        setsockopt(fd, SOL_SOCKET, SO_RCVTIMEO, &timeout, socklen_t(MemoryLayout<timeval>.size))
        guard connectUnixSocket(fd, path) == 0 else {
            let code = errno
            Darwin.close(fd)
            throw TestFailure("connect \(path): \(code)")
        }
    }

    /// Sends one framed message and returns the reply payload, or `nil` if the server closed.
    func request(_ payload: [UInt8]) async -> [UInt8]? {
        await sendRaw(SSHWriter.frame(payload))
    }

    /// Writes raw bytes and reads one frame back.
    func sendRaw(_ bytes: [UInt8]) async -> [UInt8]? {
        let fd = fd
        return await withCheckedContinuation { continuation in
            DispatchQueue.global().async {
                guard AgentServerCore.writeAll(fd, bytes) else { return continuation.resume(returning: nil) }
                continuation.resume(returning: AgentServerCore.readFrame(fd))
            }
        }
    }

    func close() { Darwin.close(fd) }
}

/// `connect(2)` to a Unix socket path.
func connectUnixSocket(_ fd: Int32, _ path: String) -> Int32 {
    var address = sockaddr_un()
    address.sun_family = sa_family_t(AF_UNIX)
    let bytes = Array(path.utf8)
    withUnsafeMutableBytes(of: &address.sun_path) { $0.copyBytes(from: bytes.prefix($0.count - 1)) }
    address.sun_len = UInt8(MemoryLayout<sockaddr_un>.size)
    return withUnsafePointer(to: &address) {
        $0.withMemoryRebound(to: sockaddr.self, capacity: 1) { connect(fd, $0, socklen_t(MemoryLayout<sockaddr_un>.size)) }
    }
}

/// Collects a server's events in the background; tests poll with `wait(for:)`.
final class EventRecorder: Sendable {
    private let events = Mutex<[AgentEvent]>([])
    private let task = Mutex<Task<Void, Never>?>(nil)

    init(_ stream: AsyncStream<AgentEvent>) {
        let collector = Task { [weak self] in
            for await event in stream { self?.events.withLock { $0.append(event) } }
        }
        task.withLock { $0 = collector }
    }

    var all: [AgentEvent.Kind] { events.withLock { $0.map(\.kind) } }

    /// Waits until `predicate` holds for the events so far, or the timeout passes.
    @discardableResult
    func wait(timeout: Duration = .seconds(5), for predicate: ([AgentEvent.Kind]) -> Bool) async -> Bool {
        let deadline = ContinuousClock.now + timeout
        while ContinuousClock.now < deadline {
            if predicate(all) { return true }
            try? await Task.sleep(for: .milliseconds(20))
        }
        return predicate(all)
    }

    func stop() { task.withLock { $0?.cancel() } }
}
