/// An authorizer that records requests and answers with a fixed decision.
final class RecordingAuthorizer: SigningAuthorizer {
    private let state: Mutex<(decision: SigningDecision, requests: [SignRequest])>

    init(_ decision: SigningDecision = .allow) {
        state = Mutex((decision, []))
    }

    func authorize(_ request: SignRequest) async -> SigningDecision {
        state.withLock {
            $0.requests.append(request)
            return $0.decision
        }
    }

    var requests: [SignRequest] { state.withLock { $0.requests } }
}

/// A user-presence verifier with scripted answers and an optional delay.
final class ScriptedVerifier: UserPresenceVerifier {
    private let state: Mutex<(answer: Bool, reasons: [String])>
    private let delay: Duration

    init(answer: Bool, delay: Duration = .zero) {
        state = Mutex((answer, []))
        self.delay = delay
    }

    func verifyUserPresence(reason: String) async -> Bool {
        let answer = state.withLock {
            $0.reasons.append(reason)
            return $0.answer
        }
        if delay > .zero { try? await Task.sleep(for: delay) }
        return answer
    }

    func setAnswer(_ answer: Bool) { state.withLock { $0.answer = answer } }
    var callCount: Int { state.withLock { $0.reasons.count } }
    var reasons: [String] { state.withLock { $0.reasons } }
}

