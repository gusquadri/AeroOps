import AeroCore
import Darwin
import Foundation

/// Renders and writes `~/.aeroops/ssh_config`, one block per host.
///
/// ```text
/// Host aero-<host-id>
///   HostName 10.0.0.12
///   User deploy
///   Port 22
///   IdentityAgent /Users/me/.aeroops/agent.sock
///   IdentityFile /Users/me/.aeroops/pub/<key-id>.pub
///   IdentitiesOnly yes
///   UserKnownHostsFile /Users/me/.aeroops/known_hosts
///   StrictHostKeyChecking yes
///   ControlMaster auto
///   ControlPath /Users/me/.aeroops/cm/%C
///   ControlPersist 10m
///   ServerAliveInterval 15
///   ServerAliveCountMax 3
///   ConnectTimeout 8
///   LogLevel ERROR
/// ```
///
/// - Paths are written absolute rather than as `~/...`: ssh expands `~` from the password
///   database, which could disagree with the home directory the app (and KeyAgent's socket) uses.
/// - No `BatchMode` here, because terminal tabs are interactive. ``SSHRunner`` passes
///   `-o BatchMode=yes` for background commands.
/// - A host without a key gets `IdentityFile none`: ssh then offers no public key at all (neither
///   agent keys nor `~/.ssh/id_*`), so only interactive methods remain, in a terminal tab.
/// - With ``SSHContext/AgentChoice/system`` every host gets `IdentityAgent SSH_AUTH_SOCK`,
///   `IdentityFile none` and `IdentitiesOnly no`: ssh offers the keys the system agent holds and
///   reads no key files.
/// - Every value is validated; newlines, control characters, quotes, backslashes and `$` are
///   rejected, `%` is escaped as `%%` where ssh expands tokens, and anything outside a plain
///   character set is double-quoted. An invalid host is left out and reported in
///   ``SSHConfigRendering/rejected`` instead of breaking every other host.
public struct SSHConfigWriter: Sendable {
    public let context: SSHContext
    /// How hosts authenticate. Always ``IdentityMode/agent`` in the app.
    var identity: IdentityMode = .agent

    /// Test-only escape hatch: integration tests log in with a throwaway private key file
    /// instead of the in-app agent. Internal on purpose, so the app cannot point ssh at key files.
    enum IdentityMode: Sendable, Hashable {
        case agent
        case privateKeyFileForTesting(URL)
    }

    /// The comment at the top of the generated file.
    public static let header = "# Generated by AeroOps. Do not edit: this file is rewritten whenever hosts change."

    /// Bytes ssh adds to a ControlPath while creating the socket: `/` + 40-hex `%C` + `.` + 16 random.
    static let controlSocketSuffixLength = 1 + 40 + 1 + 16
    /// `sun_path` holds 104 bytes including the terminating NUL.
    static let maxSocketPathLength = 103

    public init(context: SSHContext = .standard) {
        self.context = context
    }

    /// Checks that `host` can be written to the config; throws the first problem found.
    public func validate(_ host: RemoteHost) throws(SSHConfigError) {
        _ = try block(for: host)
    }

    /// Renders the whole file. Throws only for problems that affect every host (paths);
    /// per-host problems land in ``SSHConfigRendering/rejected``.
    public func render(_ hosts: [RemoteHost]) throws(SSHConfigError) -> SSHConfigRendering {
        try validatePaths()
        var blocks: [String] = []
        var included: [RemoteHost.ID] = []
        var rejected: [RemoteHost.ID: SSHConfigError] = [:]
        for host in hosts {
            do {
                blocks.append(try block(for: host))
                included.append(host.id)
            } catch {
                rejected[host.id] = error
            }
        }
        let text = ([Self.header] + blocks).joined(separator: "\n\n") + "\n"
        return SSHConfigRendering(text: text, included: included, rejected: rejected)
    }

    /// Creates `~/.aeroops` (0700), `cm/` (0700) and `pub/` (0700), then atomically replaces
    /// `ssh_config` (0600) with the rendering of `hosts`.
    @discardableResult
    public func write(_ hosts: [RemoteHost]) throws(SSHConfigError) -> SSHConfigRendering {
        let rendering = try render(hosts)
        try prepareDirectories()
        do {
            try FileSystem.writeAtomically(Data(rendering.text.utf8), to: context.configFile, permissions: 0o600)
        } catch {
            throw .fileSystem(error.description)
        }
        return rendering
    }

    /// Creates the runtime directories with owner-only permissions.
    public func prepareDirectories() throws(SSHConfigError) {
        let paths = context.paths
        do {
            try FileSystem.ensureDirectory(paths.dotDirectory, permissions: 0o700)
            try FileSystem.ensureDirectory(paths.controlMasterDirectory, permissions: 0o700)
            try FileSystem.ensureDirectory(paths.publicKeysDirectory, permissions: 0o700)
        } catch {
            throw .fileSystem(error.description)
        }
    }

    // MARK: - Rendering

    private func validatePaths() throws(SSHConfigError) {
        let controlDirectory = context.controlMasterDirectory.filePath.trimmingSuffix("/")
        if controlDirectory.utf8.count + Self.controlSocketSuffixLength > Self.maxSocketPathLength {
            throw .socketPathTooLong(controlDirectory + "/%C")
        }
        if context.agentSocket.filePath.utf8.count > Self.maxSocketPathLength {
            throw .socketPathTooLong(context.agentSocket.filePath)
        }
    }

    private func block(for host: RemoteHost) throws(SSHConfigError) -> String {
        guard HostValidation.isValidAddress(host.address) else { throw .invalidAddress(host.address) }
        guard HostValidation.isValidUser(host.user) else { throw .invalidUser(host.user) }
        guard (1...65535).contains(host.port) else { throw .invalidPort(host.port) }

        let paths = context.paths
        let identityAgent: String
        let identityFile: String
        var identitiesOnly = "yes"
        switch identity {
        case .agent where context.agent == .system:
            if let keyId = host.keyId, !HostValidation.isValidKeyID(keyId) { throw .invalidKeyID(keyId) }
            identityAgent = "SSH_AUTH_SOCK"
            identityFile = "none"
            identitiesOnly = "no"
        case .agent:
            identityAgent = try ConfigValue.path(context.agentSocket)
            if let keyId = host.keyId {
                guard HostValidation.isValidKeyID(keyId) else { throw .invalidKeyID(keyId) }
                identityFile = try ConfigValue.path(paths.publicKeysDirectory.appending(path: "\(keyId).pub"))
            } else {
                identityFile = "none"
            }
        case .privateKeyFileForTesting(let key):
            identityAgent = "none"
            identityFile = try ConfigValue.path(key)
        }
        let controlDirectory = try ConfigValue.path(context.controlMasterDirectory, trimmingTrailingSlash: true)
        let controlPath = ConfigValue.appendingUnquoted(controlDirectory, "/%C")

        let lines: [(String, String)] = [
            ("HostName", try ConfigValue.render(host.address, expandsTokens: true)),
            ("User", try ConfigValue.render(host.user, expandsTokens: false)),
            ("Port", String(host.port)),
            ("IdentityAgent", identityAgent),
            ("IdentityFile", identityFile),
            ("IdentitiesOnly", identitiesOnly),
            ("UserKnownHostsFile", try ConfigValue.path(context.knownHostsFile)),
            ("StrictHostKeyChecking", "yes"),
            ("ControlMaster", "auto"),
            ("ControlPath", controlPath),
            ("ControlPersist", "10m"),
            ("ServerAliveInterval", "15"),
            ("ServerAliveCountMax", "3"),
            ("ConnectTimeout", "8"),
            ("LogLevel", "ERROR"),
        ]
        return (["Host \(host.sshAlias)"] + lines.map { "  \($0.0) \($0.1)" }).joined(separator: "\n")
    }
}

/// The result of ``SSHConfigWriter/render(_:)``.
public struct SSHConfigRendering: Sendable, Hashable {
    /// The complete file contents.
    public var text: String
    /// Hosts written to the file, in input order.
    public var included: [RemoteHost.ID]
    /// Hosts left out, with the reason. Show these in Settings › Hosts.
    public var rejected: [RemoteHost.ID: SSHConfigError]
}

/// Why a host (or the whole config) could not be written.
public enum SSHConfigError: Error, Sendable, Hashable, LocalizedError {
    /// Not a DNS name or IP address (allowed: letters, digits, `.`, `-`, `_`, `:`, `%`).
    case invalidAddress(String)
    /// Not a plain user name (allowed: letters, digits, `.`, `_`, `-`, `@`).
    case invalidUser(String)
    /// Outside 1...65535.
    case invalidPort(Int)
    /// Key ids name files in `pub/`, so they must be plain file names.
    case invalidKeyID(String)
    /// A path contains characters ssh_config cannot represent safely.
    case invalidPath(String)
    /// A Unix socket path would exceed macOS's 104-byte `sun_path` limit.
    case socketPathTooLong(String)
    /// Creating a directory or writing the file failed.
    case fileSystem(String)

    public var errorDescription: String? {
        switch self {
        case .invalidAddress(let value): "“\(value)” is not a valid host name or IP address."
        case .invalidUser(let value): "“\(value)” is not a valid user name."
        case .invalidPort(let value): "Port \(value) is outside 1–65535."
        case .invalidKeyID(let value): "Key id “\(value)” is not a valid file name."
        case .invalidPath(let value): "The path “\(value)” cannot be used in ssh_config."
        case .socketPathTooLong(let value): "The socket path “\(value)” is longer than macOS allows (104 bytes)."
        case .fileSystem(let reason): "Could not write the SSH configuration: \(reason)"
        }
    }
}

/// Character rules for user-supplied host fields. Shared with ``HostKeyScanner``.
enum HostValidation {
    /// DNS names, IPv4, and IPv6 (unbracketed, optional `%zone`). No leading `-` or `.`.
    static func isValidAddress(_ value: String) -> Bool {
        guard let first = value.utf8.first, value.utf8.count <= 255,
              first != UInt8(ascii: "-"), first != UInt8(ascii: ".") else { return false }
        return value.utf8.allSatisfy { isAlphanumeric($0) || "._-:%".utf8.contains($0) }
    }

    /// POSIX-ish user names plus `@` (directory users). No leading `-`.
    static func isValidUser(_ value: String) -> Bool {
        guard let first = value.utf8.first, value.utf8.count <= 256, first != UInt8(ascii: "-") else { return false }
        return value.utf8.allSatisfy { isAlphanumeric($0) || "._-@".utf8.contains($0) }
    }

    /// A plain file name: letters, digits, `.`, `_`, `-`; no leading `.` or `-`.
    static func isValidKeyID(_ value: String) -> Bool {
        guard let first = value.utf8.first, value.utf8.count <= 128,
              first != UInt8(ascii: "-"), first != UInt8(ascii: ".") else { return false }
        return value.utf8.allSatisfy { isAlphanumeric($0) || "._-".utf8.contains($0) }
    }

    private static func isAlphanumeric(_ byte: UInt8) -> Bool {
        switch byte {
        case UInt8(ascii: "A")...UInt8(ascii: "Z"), UInt8(ascii: "a")...UInt8(ascii: "z"), UInt8(ascii: "0")...UInt8(ascii: "9"):
            true
        default:
            false
        }
    }
}

/// Encoding of a single ssh_config (or `-o`) argument.
enum ConfigValue {
    /// Characters that never need quoting.
    private static let plain = Set("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-._/:@+,%".unicodeScalars)

    /// Renders `value` as one ssh_config argument.
    ///
    /// - Throws for empty values, control characters (newlines included), `"` and `\`.
    /// - `expandsTokens`: the directive expands `%` tokens and `${VAR}`, so `%` becomes `%%` and
    ///   `$` is rejected.
    /// - Values with anything outside a plain character set are double-quoted, which ssh's
    ///   argument splitter (OpenSSH 8.7+) reads back as one word.
    static func render(_ value: String, expandsTokens: Bool) throws(SSHConfigError) -> String {
        guard !value.isEmpty else { throw .invalidPath(value) }
        for scalar in value.unicodeScalars {
            if scalar.value < 0x20 || scalar.value == 0x7F || scalar == "\"" || scalar == "\\" {
                throw .invalidPath(value)
            }
            if expandsTokens && scalar == "$" { throw .invalidPath(value) }
        }
        let escaped = expandsTokens ? value.replacing("%", with: "%%") : value
        return escaped.unicodeScalars.allSatisfy(plain.contains) ? escaped : "\"\(escaped)\""
    }

    /// Renders an absolute file path (token-expanding directives: IdentityFile, ControlPath, ...).
    static func path(_ url: URL, trimmingTrailingSlash: Bool = false) throws(SSHConfigError) -> String {
        var path = url.filePath
        if trimmingTrailingSlash { path = path.trimmingSuffix("/") }
        guard path.hasPrefix("/") else { throw .invalidPath(path) }
        return try render(path, expandsTokens: true)
    }

    /// Appends a raw (already escaped) suffix such as `/%C` inside any quotes of `rendered`.
    static func appendingUnquoted(_ rendered: String, _ suffix: String) -> String {
        if rendered.hasSuffix("\""), rendered.hasPrefix("\"") {
            return String(rendered.dropLast()) + suffix + "\""
        }
        return rendered + suffix
    }
}

extension String {
    func trimmingSuffix(_ suffix: String) -> String {
        var result = self
        while result.count > 1, result.hasSuffix(suffix) { result.removeLast(suffix.count) }
        return result
    }
}
